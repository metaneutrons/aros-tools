    #[test]
    fn the_two_source_tree_aggregates_keep_their_declared_output_shapes() {
        let root = source_tree();
        let mut files = Vec::new();
        for entry in fs::read_dir(root.join("arch")).unwrap() {
            let entry = entry.unwrap();
            if !entry.file_type().unwrap().is_dir() {
                continue;
            }
            let relative_dir = PathBuf::from("arch")
                .join(entry.file_name())
                .join("include");
            let path = root.join(&relative_dir).join("mmakefile.src");
            if !path.is_file() {
                continue;
            }
            let content = fs::read_to_string(path).unwrap();
            if content
                .lines()
                .any(|line| line.trim().starts_with("#MM ") && !line.trim().starts_with("#MM-"))
                && content.contains("$(HOSTGENDIR)/tools/")
            {
                files.push((relative_dir, content));
            }
        }
        let mut declarations = Vec::new();
        let mut total_outputs = 0;
        for (relative_dir, content) in files {
            let scope = collect_vars(&content);
            let dirs = DirVars::load(&root);
            let (found, rejections) = collect(&content, &relative_dir, &scope, &dirs, &root, None);
            assert!(
                rejections.is_empty(),
                "{}: {rejections:#?}",
                relative_dir.display()
            );
            total_outputs += found.iter().map(|decl| decl.headers.len()).sum::<usize>();
            declarations.extend(found);
        }
        assert_eq!(declarations.len(), 2, "{declarations:#?}");
        assert_eq!(total_outputs, 3, "{declarations:#?}");
        assert_eq!(
            declarations
                .iter()
                .filter(|declaration| declaration.headers.iter().any(|h| h.generated_mirror))
                .count(),
            1,
            "only the source-declared mirror is captured: {declarations:#?}"
        );
        assert!(declarations
            .iter()
            .all(|declaration| declaration.tool_source.ends_with("/gencall.c")));
    }
