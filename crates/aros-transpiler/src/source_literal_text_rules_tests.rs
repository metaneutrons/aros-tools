#[test]
fn rejects_unknown_recipe_state_and_duplicate_owner_or_output_claims() {
    let root = source_root();
    let target = target("arm", "");

    let source = generic_source();
    let mut states = vec![ConditionalTruth::True; source.lines().count()];
    let echo_line = source
        .lines()
        .position(|line| line.contains("#define VERSION"))
        .expect("last output echo");
    states[echo_line] = ConditionalTruth::Unknown;
    let (declarations, rejections) = scan(
        &root,
        Path::new("compiler/example"),
        &source,
        &target,
        Some(&states),
    );
    assert!(declarations.is_empty());
    assert!(rejections
        .iter()
        .any(|item| item.reason.contains("undecided Make conditional")));

    let duplicate_owner = format!(
        "{}#MM\nfixture-generated : $(GENDIR)/$(CURDIR)/generated.h\n",
        generic_source()
    );
    let (declarations, rejections) = scan(
        &root,
        Path::new("compiler/example"),
        &duplicate_owner,
        &target,
        None,
    );
    assert!(declarations.is_empty());
    assert!(rejections
        .iter()
        .any(|item| item.reason.contains("duplicate active aggregates")));

    let duplicate_output = format!(
        "{}#MM\nother-generated : $(GENDIR)/$(CURDIR)/generated.h\n",
        generic_source()
    );
    let (declarations, rejections) = scan(
        &root,
        Path::new("compiler/example"),
        &duplicate_output,
        &target,
        None,
    );
    assert!(declarations.is_empty());
    assert!(rejections
        .iter()
        .any(|item| item.reason.contains("duplicate active owners")));
}

#[test]
fn requires_bare_marker_and_recipe_file_provider_relationship() {
    let root = source_root();
    let target = target("arm", "");
    let inline = generic_source().replace(
        "#MM\nfixture-generated : $(GENDIR)/$(CURDIR)/generated.h",
        "#MM- fixture-generated : $(GENDIR)/$(CURDIR)/generated.h",
    );
    let (declarations, rejections) =
        scan(&root, Path::new("compiler/example"), &inline, &target, None);
    assert!(declarations.is_empty());
    assert!(rejections
        .iter()
        .any(|item| item.reason.contains("bare `#MM` marker")));

    let recipe_on_aggregate = generic_source().replace(
        "fixture-generated : $(GENDIR)/$(CURDIR)/generated.h\n",
        "fixture-generated : $(GENDIR)/$(CURDIR)/generated.h\n\t@$(NOP)\n",
    );
    let (declarations, rejections) = scan(
        &root,
        Path::new("compiler/example"),
        &recipe_on_aggregate,
        &target,
        None,
    );
    assert!(declarations.is_empty());
    assert!(rejections
        .iter()
        .any(|item| item.reason.contains("no ordinary Make recipe")));
}
