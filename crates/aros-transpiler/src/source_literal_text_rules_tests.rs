fn source_root() -> TempDir {
    let root = tempfile::tempdir().expect("temporary source root");
    fs::create_dir_all(root.path().join("config")).expect("config directory");
    fs::write(root.path().join("config/make.cfg.in"), "ECHO := echo\n")
        .expect("source echo binding");
    root
}

fn scan(
    root: &TempDir,
    rel_dir: &Path,
    source: &str,
    target: &TargetContext,
    line_states: Option<&[ConditionalTruth]>,
) -> (
    Vec<SourceLiteralTextRuleDecl>,
    Vec<SourceLiteralTextRuleRejection>,
) {
    let scope = collect_vars_with_context(source, target);
    let dirs = DirVars::load(root.path());
    collect_with_context(source, root.path(), rel_dir, &scope, &dirs, line_states)
}

fn generic_source() -> String {
    r##"VERSION := 1.2
#MM
fixture-generated : $(GENDIR)/$(CURDIR)/generated.h
$(GENDIR)/$(CURDIR)/generated.h : $(SRCDIR)/$(CURDIR)/mmakefile.src
	@$(ECHO) "Generating generated.h"
	%mkdir_q dir=$(GENDIR)/$(CURDIR)
	@$(ECHO) "// Source: $(SRCDIR)/$(CURDIR)/mmakefile.src" > $@
	@$(ECHO) "// CPU: $(AROS_TARGET_CPU)" >> $@
	@$(ECHO) "#define VERSION $(VERSION)" >> $@
"##
    .to_owned()
}

fn softfloat_source() -> String {
    r##"ifneq (,$(filter arm armeb aarch64,$(AROS_TARGET_CPU)))
ifeq (be,$(AROS_TARGET_VARIANT))
SOFTFLOATLE = 0
endif
endif
ifeq (,$(SOFTFLOATLE))
SOFTFLOATLE = 1
endif
#MM
linklibs-softfloat-genfiles : $(GENDIR)/$(CURDIR)/platform.h
$(GENDIR)/$(CURDIR)/platform.h : $(SRCDIR)/$(CURDIR)/mmakefile.src
	@$(ECHO) "Generating platform.h"
	%mkdir_q dir=$(GENDIR)/$(CURDIR)
	@$(ECHO) "// Autogenerated from $(SRCDIR)/$(CURDIR)/mmakefile.src - do not edit" > $@
	@$(ECHO) "// AROS libsoftfloat configuration for $(AROS_TARGET_CPU)" >> $@
	@$(ECHO) "#define LITTLEENDIAN $(SOFTFLOATLE)" >> $@
"##
    .to_owned()
}

fn target(cpu: &str, variant: &str) -> TargetContext {
    TargetContext {
        cpu: Some(cpu.to_owned()),
        platform: Some("pc".to_owned()),
        family: Some("pc".to_owned()),
        variant: Some(variant.to_owned()),
        ..TargetContext::default()
    }
}

#[test]
fn scans_generic_owner_and_writes_make_evaluated_lines_with_newlines() {
    let root = source_root();
    let source = generic_source();
    let (declarations, rejections) = scan(
        &root,
        Path::new("compiler/example"),
        &source,
        &target("arm", ""),
        None,
    );
    assert!(rejections.is_empty(), "{rejections:#?}");
    let [declaration] = declarations.as_slice() else {
        panic!("expected one generic literal text declaration: {declarations:#?}");
    };
    assert_eq!(declaration.owner, "fixture-generated");
    assert_eq!(declaration.file, "compiler/example/mmakefile.src");
    assert_eq!(declaration.line, 2);
    assert_eq!(
        declaration.output,
        "${AROS_BUILD_DIR}/gen/compiler/example/generated.h"
    );
    assert_eq!(
        declaration.text,
        "// Source: ${AROS_SOURCE_DIR}/compiler/example/mmakefile.src\n\
         // CPU: arm\n\
         #define VERSION 1.2\n"
    );
    assert!(declaration.file_sha256.is_empty());
}

